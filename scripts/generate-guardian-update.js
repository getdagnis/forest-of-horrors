const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");
const sourceDir = path.join(repoRoot, "generated", "sources");
const outputFile = path.join(repoRoot, "generated", "guardian-update.lua");

function readSource(name) {
  return fs.readFileSync(path.join(sourceDir, name), "utf8").replace(/\r\n/g, "\n");
}

function luaLongString(source) {
  let equals = "";
  while (source.includes(`]${equals}]`)) {
    equals += "=";
  }
  return `[${equals}[\n${source}\n]${equals}]`;
}

const guardianSource = readSource("GuardianLegDamage.lua");

const command = `-- Generated by scripts/generate-guardian-update.js
-- Paste this into Roblox Studio Command Bar, then save the place.

local guardianSource = ${luaLongString(guardianSource)}

local updated = 0
local attackDamageChanged = 0

for _, model in workspace:GetDescendants() do
\tif model:IsA("Model") and model.Name == "weird monster thing" then
\t\tlocal config = model:FindFirstChild("Configuration")
\t\tif config then
\t\t\tlocal attackDamage = config:FindFirstChild("AttackDamage")
\t\t\tif attackDamage and attackDamage:IsA("NumberValue") then
\t\t\t\tattackDamage.Value = 0
\t\t\t\tattackDamageChanged += 1
\t\t\tend
\t\tend

\t\tlocal oldScript = model:FindFirstChild("GuardianLegDamage")
\t\tif oldScript then
\t\t\toldScript:Destroy()
\t\tend

\t\tlocal scriptObject = Instance.new("Script")
\t\tscriptObject.Name = "GuardianLegDamage"
\t\tscriptObject.Source = guardianSource
\t\tscriptObject.Parent = model

\t\tupdated += 1
\tend
end

print("Guardian update complete")
print("Updated weird monster thing models:", updated)
print("AttackDamage values set to 0:", attackDamageChanged)
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, command);
console.log(`Wrote ${outputFile}`);

