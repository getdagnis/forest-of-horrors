const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");
const sourceDir = path.join(repoRoot, "generated", "sources");
const outputFile = path.join(repoRoot, "generated", "monster-bomb-update.lua");

function readSource(name) {
  return fs.readFileSync(path.join(sourceDir, name), "utf8").replace(/\r\n/g, "\n");
}

function luaLongString(source) {
  let equals = "";
  while (source.includes(`]${equals}]`)) {
    equals += "=";
  }
  return `[${equals}[\n${source}\n]${equals}]`;
}

const configSource = readSource("MonsterBombConfig.lua");
const systemSource = readSource("MonsterBombSystem.lua");

const command = `-- Generated by scripts/generate-monster-bomb-update.js
-- Paste this into Roblox Studio Command Bar, then save the place.

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerScriptService = game:GetService("ServerScriptService")

local monsterBombConfigSource = ${luaLongString(configSource)}

local monsterBombSystemSource = ${luaLongString(systemSource)}

local function upsertLua(parent, className, name, source)
\tlocal object = parent:FindFirstChild(name)

\tif not object or not object:IsA(className) then
\t\tif object then
\t\t\tobject:Destroy()
\t\tend

\t\tobject = Instance.new(className)
\t\tobject.Name = name
\t\tobject.Parent = parent
\tend

\tobject.Source = source
\treturn object
end

upsertLua(ReplicatedStorage, "ModuleScript", "MonsterBombConfig", monsterBombConfigSource)
upsertLua(ServerScriptService, "Script", "MonsterBombSystem", monsterBombSystemSource)

local monsterManager = ReplicatedStorage:FindFirstChild("MonsterManager")
if monsterManager and monsterManager:IsA("ModuleScript") then
\tlocal source = monsterManager.Source
\tlocal updatedSource, replacements = source:gsub(
\t\t'%["Monster"%]%s*=%s*{%s*hp%s*=%s*%d+%s*,%s*points%s*=%s*(%d+)%s*}',
\t\t'["Monster"] = { hp = 400, points = %1 }'
\t)

\tif replacements > 0 then
\t\tmonsterManager.Source = updatedSource
\t\tprint("Updated MonsterManager Monster HP to 400")
\telse
\t\twarn("MonsterManager Monster config line was not found. Check it manually: [\\"Monster\\"] = { hp = 400, points = 3 }")
\tend
else
\twarn("ReplicatedStorage.MonsterManager was not found")
end

local updatedModels = 0
local removedScripts = 0

for _, model in workspace:GetDescendants() do
\tif model:IsA("Model") and model.Name == "Monster" then
\t\tlocal oldScript = model:FindFirstChild("MonsterBombScript")
\t\tif oldScript then
\t\t\toldScript:Destroy()
\t\t\tremovedScripts += 1
\t\tend

\t\tlocal humanoid = model:FindFirstChildOfClass("Humanoid")
\t\tif not humanoid then
\t\t\thumanoid = Instance.new("Humanoid")
\t\t\thumanoid.Name = "Humanoid"
\t\t\thumanoid.Parent = model
\t\tend

\t\thumanoid.MaxHealth = 400
\t\thumanoid.Health = 400
\t\thumanoid.BreakJointsOnDeath = false
\t\thumanoid.DisplayDistanceType = Enum.HumanoidDisplayDistanceType.None

\t\tupdatedModels += 1
\tend
end

print("MonsterBomb update complete")
print("Updated Monster models:", updatedModels)
print("Removed per-model MonsterBombScript scripts:", removedScripts)
print("Created/updated ReplicatedStorage.MonsterBombConfig")
print("Created/updated ServerScriptService.MonsterBombSystem")
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, command);
console.log(`Wrote ${outputFile}`);

